/* --------------------------------------------------------------- Sizing ---
 * Per-value stock is modelled because a sold-out size is the single most
 * common variant state in apparel — showing it struck through is far better
 * than letting someone pick it and fail at checkout.
 * -------------------------------------------------------------------------- */

const APPAREL_LABELS: Record<string, string> = {
  XS: "Extra small",
  S: "Small",
  M: "Medium",
  L: "Large",
  XL: "Extra large",
  XXL: "Double extra large",
};

/** `soldOut` lists the values that are unavailable for this particular item. */
function apparel(values: string[], soldOut: string[] = []): SizeGroup {
  return {
    system: "apparel",
    options: values.map((value) => ({
      value,
      label: APPAREL_LABELS[value] ?? value,
      inStock: !soldOut.includes(value),
    })),
    guideNote: "Fits true to size. Measurements are in the size chart.",
  };
}

function footwear(values: number[], soldOut: number[] = []): SizeGroup {
  return {
    system: "footwear",
    options: values.map((value) => ({
      value: String(value),
      label: `EU ${value}`,
      inStock: !soldOut.includes(value),
    })),
    guideNote: "European sizing. If you are between sizes, take the larger.",
  };
}


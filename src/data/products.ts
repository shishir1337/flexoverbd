import type { ImageAsset, Product, SizeGroup } from "./types";

/**
 * Demo catalogue.
 *
 * Two rules shaped it:
 *
 *  1. Prices are in BDT and benchmarked against what these categories actually
 *     sell for online in Bangladesh, so the client reviews believable numbers.
 *  2. Every product is backed by a real photograph. Titles describe what is
 *     genuinely in the frame — no product claims something the picture does not
 *     show, because a catalogue that lies to itself is useless for judging
 *     layout.
 *
 * The photos are demo stand-ins pulled from a public prototyping dataset
 * (`pnpm images:products`). They are placeholders for the client's own product
 * photography and must be replaced before launch — see README.
 */

const SHOOT =
  "centred on a seamless off-white studio background with a soft contact shadow, even softbox lighting, crisp edge-to-edge focus, premium e-commerce catalogue photography, square 1:1 crop, no text, no logos, no watermark";

function img(
  slug: string,
  alt: string,
  subject: string,
  demoSource: string,
): ImageAsset {
  return {
    src: `/images/products/${slug}.jpg`,
    alt,
    width: 800,
    height: 800,
    demoSource,
    prompt: `Studio product photograph of ${subject}, ${SHOOT}.`,
  };
}

